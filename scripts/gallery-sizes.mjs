// Writes lib/gallery-sizes.ts: the displayed width and height of every photo in
// public/images/gallery/all, so the portfolio grid can reserve space before photos load.
// Run after adding photos: node scripts/gallery-sizes.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const { imageSize } = createRequire(import.meta.url)("next/dist/compiled/image-size");
const DIR = "public/images/gallery/all";

const lines = readdirSync(DIR)
  .filter((file) => /\.(jpe?g|png|webp)$/i.test(file))
  .sort()
  .map((file) => {
    const { width, height, orientation } = imageSize(`${DIR}/${file}`);
    // EXIF orientations 5–8 are rotated 90°, so the photo displays with width and height swapped.
    const [w, h] = orientation >= 5 ? [height, width] : [width, height];
    return `  ${JSON.stringify(file)}: [${w}, ${h}],`;
  });

writeFileSync(
  "lib/gallery-sizes.ts",
  `// Generated by scripts/gallery-sizes.mjs — rerun it after adding gallery photos.\n` +
    `export const GALLERY_SIZES: Record<string, [width: number, height: number]> = {\n${lines.join("\n")}\n};\n`
);
console.log(`lib/gallery-sizes.ts: ${lines.length} photos`);
